def get_planning_instruction() -> str:
    """
    提供 Autonomy 的动态规划指令。
    要求模型维护一个可见的任务账本。
    """
    return """[动态规划协议 - PLANNING PROTOCOL]
对于复杂任务，你必须在 <plan> 标签中维护一个任务账本：
<plan>
- [x] 已完成的步骤
- [/] 正在执行的步骤
- [ ] 待执行的步骤
</plan>

[准则]
1. 颗粒度：每个步骤必须是可验证的原子操作。
2. 动态调整：每轮执行后，根据工具的反馈（Observation）实时更新状态。
3. 退出逻辑：当所有必要步骤均标记为 [x] 时，应立即转向合成最终答复。"""
